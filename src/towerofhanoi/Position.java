package towerofhanoi;

/**
 * Represents all the possible positions in the Tower of Hanoi game.
 * 
 * @author G.J. Hu
 * @version 2025.08.14
 *
 */
public enum Position
{
    /**
     * The leftmost tower
     */
    LEFT,
    /**
     * The middle tower
     */
    CENTER,
    /**
     * The rightmost tower
     */
    RIGHT,
    /**
     * A default value, no specific position is specified
     */
    DEFAULT;
}
